/// @file test_time_source.cpp
/// @brief Regression tests for lf_clock_init / lf_time_advance_ros_clock.
///
/// _lf_get_environments is normally code-generated by lfc into the final
/// binary.  Here we provide a local stub that injects a synthetic logical
/// time so the tests don't depend on the lfc toolchain.

#include <gtest/gtest.h>
#include <rcl/time.h>

#include "../src/time_source.hpp"
#include "rclcpp/rclcpp.hpp"

// ── Stub for lfc-generated symbol ────────────────────────────────────────────
// _lf_get_environments is declared in reactor-c headers and is resolved at
// link time by the lfc-compiled binary.  For unit tests we provide a minimal
// stub that returns a single environment whose current_tag.time is controlled
// via g_test_logical_time below.

extern "C" {
#include "core/environment.h"  // environment_t, tag_t
}

static environment_t g_test_env;
static int64_t g_test_logical_time = 0;

extern "C" int _lf_get_environments(environment_t ** envs)
{
  g_test_env.current_tag.time = g_test_logical_time;
  *envs = &g_test_env;
  return 1;
}

// ── Test fixture ──────────────────────────────────────────────────────────────

class TimeSourceTest : public ::testing::Test
{
protected:
  static void SetUpTestSuite() {rclcpp::init(0, nullptr);}
  static void TearDownTestSuite() {rclcpp::shutdown();}

  void SetUp() override
  {
    g_test_logical_time = 0;
    ros2_lf_binding::g_lf_clock.reset();
  }
};

// ── Tests ─────────────────────────────────────────────────────────────────────

TEST_F(TimeSourceTest, ClockInitCreatesRosTimeClock)
{
  ros2_lf_binding::lf_clock_init();
  ASSERT_NE(ros2_lf_binding::g_lf_clock, nullptr);
  EXPECT_EQ(ros2_lf_binding::g_lf_clock->get_clock_type(), RCL_ROS_TIME);
}

TEST_F(TimeSourceTest, ClockInitEnablesOverride)
{
  ros2_lf_binding::lf_clock_init();
  ASSERT_NE(ros2_lf_binding::g_lf_clock, nullptr);

  bool enabled = false;
  rcl_ret_t ret =
    rcl_is_enabled_ros_time_override(ros2_lf_binding::g_lf_clock->get_clock_handle(), &enabled);
  EXPECT_EQ(ret, RCL_RET_OK);
  EXPECT_TRUE(enabled);
}

TEST_F(TimeSourceTest, AdvanceClockSetsLogicalTime)
{
  ros2_lf_binding::lf_clock_init();
  ASSERT_NE(ros2_lf_binding::g_lf_clock, nullptr);

  const int64_t expected_ns = 1'234'567'890LL;
  g_test_logical_time = expected_ns;

  ros2_lf_binding::lf_time_advance_ros_clock();

  // g_lf_clock->now() reads from the ROS time override we set.
  auto actual_ns = ros2_lf_binding::g_lf_clock->now().nanoseconds();
  EXPECT_EQ(actual_ns, expected_ns);
}

TEST_F(TimeSourceTest, AdvanceClockMultipleTimes)
{
  ros2_lf_binding::lf_clock_init();
  ASSERT_NE(ros2_lf_binding::g_lf_clock, nullptr);

  for (int64_t t : {100'000'000LL, 200'000'000LL, 300'000'000LL}) {
    g_test_logical_time = t;
    ros2_lf_binding::lf_time_advance_ros_clock();
    EXPECT_EQ(ros2_lf_binding::g_lf_clock->now().nanoseconds(), t);
  }
}

TEST_F(TimeSourceTest, AdvanceWithNoClockIsNoop)
{
  // g_lf_clock is null (reset in SetUp); must not crash.
  ASSERT_EQ(ros2_lf_binding::g_lf_clock, nullptr);
  EXPECT_NO_THROW(ros2_lf_binding::lf_time_advance_ros_clock());
}

TEST_F(TimeSourceTest, AdvanceWithZeroTimeIsSkipped)
{
  ros2_lf_binding::lf_clock_init();

  // Seed a non-zero value first.
  g_test_logical_time = 500'000'000LL;
  ros2_lf_binding::lf_time_advance_ros_clock();
  EXPECT_EQ(ros2_lf_binding::g_lf_clock->now().nanoseconds(), 500'000'000LL);

  // Now advance with logical_ns == 0; the clock value must not change.
  g_test_logical_time = 0;
  ros2_lf_binding::lf_time_advance_ros_clock();
  EXPECT_EQ(ros2_lf_binding::g_lf_clock->now().nanoseconds(), 500'000'000LL);
}
