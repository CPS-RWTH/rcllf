"""Scaffold ``config/execution.reference.yaml`` + ``config/execution.yaml``.

Two files:

- ``execution.reference.yaml`` — write-only, fully generated documentation
  as a file (every node/subscription with its effective default + the
  registry ``doc`` line as comments). Regenerated every run, never read back.
- ``execution.yaml`` — user-owned, sparse, machine-readable. First scaffold
  writes ``schema_version`` + an empty ``defaults:`` + a pointer comment to
  the reference file. This tool NEVER rewrites an existing ``execution.yaml``
  (the whole point of the reference/sparse split); stale entries (nodes or
  topics that no longer exist in the model) are reported as diagnostics on
  stdout, never edited away.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
from typing import TYPE_CHECKING

import yaml

from colcon_lf.exec_config.model import ExecConfig
from colcon_lf.exec_config.policies import (
    REGISTRY,
    SCOPE_NODES,
    SCOPE_SUBSCRIPTIONS,
    input_name,
)
from colcon_lf.exec_config.yaml_schema import SCHEMA_VERSION

if TYPE_CHECKING:
    from colcon_lf.graph.models import SystemGraph

REFERENCE_FILENAME = "execution.reference.yaml"
SPARSE_FILENAME = "execution.yaml"


@dataclass
class ScaffoldResult:
    """Report of what a scaffold run did."""

    reference_path: Path
    sparse_path: Path
    sparse_created: bool
    stale_nodes: list[str] = field(default_factory=list)
    # (node_key, topic_key) pairs present in execution.yaml but not in the model
    stale_subscription_topics: list[tuple[str, str]] = field(default_factory=list)


def scaffold(config_dir: Path, graph: "SystemGraph", *, write: bool = True) -> ScaffoldResult:
    """Regenerate the reference file; create the sparse file if absent.

    Never touches an existing ``execution.yaml``. Returns a ``ScaffoldResult``
    describing what happened, including any stale entries found in an
    existing sparse file (reported, not edited). With ``write=False`` nothing
    is written: the result only names the paths and the stale entries of an
    existing sparse file (``colcon lf-configure --show``).
    """
    config_dir = Path(config_dir)
    reference_path = config_dir / REFERENCE_FILENAME
    sparse_path = config_dir / SPARSE_FILENAME

    if write:
        config_dir.mkdir(parents=True, exist_ok=True)
        reference_path.write_text(_emit_reference(graph), encoding="utf-8")

    sparse_created = False
    if write and not sparse_path.is_file():
        sparse_path.write_text(_emit_initial_sparse(), encoding="utf-8")
        sparse_created = True

    stale_nodes: list[str] = []
    stale_subscription_topics: list[tuple[str, str]] = []
    if not sparse_created and sparse_path.is_file():
        stale_nodes, stale_subscription_topics = _find_stale_entries(sparse_path, graph)

    return ScaffoldResult(
        reference_path=reference_path,
        sparse_path=sparse_path,
        sparse_created=sparse_created,
        stale_nodes=stale_nodes,
        stale_subscription_topics=stale_subscription_topics,
    )


def _emit_initial_sparse() -> str:
    lines = [
        f"{'schema_version'}: {SCHEMA_VERSION}",
        "# See execution.reference.yaml (regenerated every `colcon lf-configure` "
        "run) for every",
        "# node/subscription and its effective default. This file is sparse: "
        "only keys you",
        "# set here override the built-in default. Presence = set, absence = "
        "inherit.",
        "defaults: {}",
        "nodes: {}",
        "subscriptions: {}",
        "acknowledged_hazards: []",
        "",
    ]
    return "\n".join(lines)


def _emit_reference(graph: "SystemGraph") -> str:
    """Fully generated documentation-as-a-file. Never read back."""
    lines: list[str] = [
        "# GENERATED by `colcon lf-configure` — regenerated every run, never read back.",
        "# Edit config/execution.yaml instead; use the keys shown here.",
        "#",
        "# Policy keys (registry):",
    ]
    for spec in REGISTRY.values():
        default_str = _default_str(spec)
        lines.append(f"#   {input_name(spec.key)} (default: {default_str}) — {spec.doc}")
        lines.append(f"#     valid at: {', '.join(sorted(spec.scopes))}")
    lines.append("#")
    lines.append("# defaults: (global scope)")
    for spec in REGISTRY.values():
        lines.append(f"#   {input_name(spec.key)}: {_default_str(spec)}")
    lines.append("#")
    lines.append("# nodes: (per-node scope; node key = system.json nodes key)")
    for node_key in sorted(graph.nodes.keys()):
        lines.append(f"#   {node_key}:")
        # Only keys actually valid in this scope; listing a defaults-only key
        # here would advertise a setting the loader rejects.
        for spec in REGISTRY.values():
            if SCOPE_NODES in spec.scopes:
                lines.append(f"#     {input_name(spec.key)}: {_default_str(spec)}")
    lines.append("#")
    lines.append(
        "# subscriptions: (per-subscription scope; topic key = "
        "SubscriberInfo.topic, may be relative)"
    )
    for node_key in sorted(graph.nodes.keys()):
        node_info = graph.nodes[node_key]
        if not node_info.subscribers:
            continue
        lines.append(f"#   {node_key}:")
        for sub in node_info.subscribers:
            lines.append(f"#     {sub.topic}:")
            for spec in REGISTRY.values():
                if SCOPE_SUBSCRIPTIONS in spec.scopes:
                    lines.append(f"#       {input_name(spec.key)}: {_default_str(spec)}")
    lines.append("")
    return "\n".join(lines)


def _default_str(spec) -> str:
    """Render a policy default for the reference file.

    A None default means "not configured here" rather than a literal value;
    showing Python's `None` in a YAML-shaped file would invite copying it in
    as a value.
    """
    if spec.default is None:
        return "(unset)"
    return repr(spec.default)


def _find_stale_entries(
    sparse_path: Path, graph: "SystemGraph"
) -> tuple[list[str], list[tuple[str, str]]]:
    """Report node/topic keys in an existing sparse file no longer in the model.

    Uses the same slash-tolerant matching as ``ExecConfig`` so a merely
    differently-slashed key is not reported as stale.
    """
    try:
        raw = yaml.safe_load(sparse_path.read_text(encoding="utf-8")) or {}
    except yaml.YAMLError:
        return [], []
    if not isinstance(raw, dict):
        return [], []

    node_keys = set(graph.nodes.keys())

    def _known_node(key: str) -> bool:
        return key in node_keys or f"/{key}" in node_keys or key.lstrip("/") in node_keys

    def _known_topic(node_key: str, topic_key: str) -> bool:
        resolved_node = None
        for candidate in (node_key, f"/{node_key}", node_key.lstrip("/")):
            if candidate in graph.nodes:
                resolved_node = candidate
                break
        if resolved_node is None:
            return False
        topics = {s.topic for s in graph.nodes[resolved_node].subscribers}
        return (
            topic_key in topics
            or f"/{topic_key}" in topics
            or topic_key.lstrip("/") in topics
        )

    stale_nodes: list[str] = []
    for node_key in (raw.get("nodes") or {}):
        if not _known_node(node_key):
            stale_nodes.append(node_key)

    stale_subscription_topics: list[tuple[str, str]] = []
    for node_key, topics in (raw.get("subscriptions") or {}).items():
        if not _known_node(node_key):
            stale_nodes.append(node_key)
            continue
        if not isinstance(topics, dict):
            continue
        for topic_key in topics:
            if not _known_topic(node_key, topic_key):
                stale_subscription_topics.append((node_key, topic_key))

    return stale_nodes, stale_subscription_topics
