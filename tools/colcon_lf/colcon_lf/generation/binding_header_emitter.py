"""Emit the ``ros2_lf_reaction_ids.h`` C header from a reaction-ID table.

Entry point: ``emit_reaction_ids_header(rid_table) -> str``

The table is a list of (rid, node_class, callback_name, kind, topic_or_service)
tuples as produced by the generator's _assign_reaction_ids pass.
"""

from __future__ import annotations

from collections import Counter

from colcon_lf.generation.lf_naming import sanitize_lf_identifier


def _rid_macro(node_class: str, callback_name: str) -> str:
    return f"RID_{sanitize_lf_identifier(node_class)}_{sanitize_lf_identifier(callback_name)}"


def _assert_unique_macros(rid_table) -> None:
    """Raise if two rid_table rows map to the same ``RID_*`` macro name."""
    owners: dict[str, list[tuple[int, str, str]]] = {}
    for rid, node_class, cb_name, *_ in rid_table:
        owners.setdefault(_rid_macro(node_class, cb_name), []).append(
            (rid, node_class, cb_name)
        )
    duplicates = {m: rows for m, rows in owners.items() if len(rows) > 1}
    if not duplicates:
        return
    detail = "; ".join(
        f"{macro} <- "
        + ", ".join(f"rid={r} key={k!r} callback={c!r}" for r, k, c in rows)
        for macro, rows in sorted(duplicates.items())
    )
    raise ValueError(
        "RID macro name collision (this is a generator bug, not a user error): "
        + detail
    )


def emit_reaction_ids_header(
    rid_table: list[tuple[int, str, str, str, str]],
) -> str:
    """Emit a C header with RID_* #defines and a topic-string table.

    Parameters
    ----------
    rid_table:
        List of ``(rid, binding_key, callback_name, kind, topic_or_service)``.
        ``topic_or_service`` is empty string for timer reactions.

    Raises
    ------
    ValueError
        If two rows produce the same ``RID_*`` macro name.  That would be a
        duplicate ``#define`` (a compile error at best, a silently aliased
        reaction at worst), so it is caught here as a loud generator-side
        tripwire — see design note section 2.
    """
    lines: list[str] = [
        "/* Auto-generated by colcon lf-generate. DO NOT EDIT. */",
        "#pragma once",
        "",
    ]

    if not rid_table:
        lines += [
            "#define RID_COUNT 0",
            "",
        ]
        return "\n".join(lines) + "\n"

    _assert_unique_macros(rid_table)

    # Emit one #define per reaction
    for rid, node_class, cb_name, kind, topic, *_ in rid_table:
        macro = _rid_macro(node_class, cb_name)
        lines.append(f"#define {macro} {rid}")

    total = len(rid_table)
    lines += [
        "",
        f"#define RID_COUNT {total}",
        "",
    ]

    # Topic/service string table (empty string for timers)
    lines.append("#ifdef ROS2_LF_DEFINE_TABLES")
    lines.append(f"const char* RID_TOPIC[{total}] = {{")
    for _rid, _nc, _cb, _kind, topic, *_ in rid_table:
        escaped = topic.replace('"', '\\"')
        lines.append(f'    "{escaped}",')
    lines.append("};")
    lines.append("#endif  /* ROS2_LF_DEFINE_TABLES */")
    lines.append("")

    return "\n".join(lines) + "\n"


# RID kinds whose reaction is driven by a ROS timer handle (node_binding.cpp).
_TIMER_KINDS = ("timer", "srv_send", "action_goal_send")


def collect_rid_table(
    class_to_reactor,  # dict[str, LFReactor]
    graph,             # SystemGraph
    binding_keys: dict[str, str] | None = None,
    timer_period_overrides: dict[str, dict[str, float]] | None = None,
) -> list[tuple[int, str, str, str, str, int, int, int, str]]:
    """Walk reactors in the same order as _assign_reaction_ids and collect rows.

    Returns list of (rid, binding_key, callback_name, kind, topic_or_service, period_ns,
    creation_index, group_index, sub_reliability). period_ns is 0 for subscriptions. creation_index is
    the position of the reaction's timer in ``NodeInfo.timers`` (timer-driven kinds) or
    of its subscription in ``NodeInfo.subscribers`` (``sub``), both in the order the
    node creates them, and -1 for other kinds. group_index is the position of that
    entity's callback group among the groups the node creates itself, -1 for the
    node's default group and -2 when unknown. ``ros2_lf_bind_node`` matches handles
    to reactions one to one, within each callback group, in creation order.
    sub_reliability is the reliability the analysis saw on a ``sub``
    reaction's subscription, empty without a value or for other kinds; the
    binding checks RCLLF-H000 and H001 on it per subscription.

    The second column is the **binding key** (``binding_key.py``) — equal to the
    C++ class name only when that class has a single instance.  It lands in
    ``RidEntry.node_class`` and in the ``RID_<key>_<callback>`` macro, matching
    the reactor name and the ``ros2_lf_bind_node`` string emitted by
    ``lf_generator.py`` for the same instance.

    ``timer_period_overrides`` must be the one ``generate_lf_system`` got: a
    timer's period_ns is its period after the ``execution.yaml`` override, as
    in the generated LF timer, else the binding finds no handle of that period
    and refuses to start.
    """
    from colcon_lf.generation.binding_key import build_binding_keys
    from colcon_lf.exec_config.policies import period_ms_to_ns
    from colcon_lf.generation.lf_generator import apply_timer_period_overrides
    from colcon_lf.generation.lf_naming import class_name_to_reactor_name

    if binding_keys is None:
        binding_keys = build_binding_keys(graph.nodes)

    # Build timer period lookup: (node_key, callback_name) -> period_ns. Keyed by
    # node, not class: an override applies to one instance of a class.
    # The binding matches a timer handle by its exact period in
    # nanoseconds, so the period is converted from the exact decimal the
    # analysis or execution.yaml wrote, floored as the generated sizing does
    # (period_ms_to_ns). ``int(period_ms * 1_000_000)`` lost a nanosecond to
    # binary rounding (8.2 ms gave 8199999 ns). 0 stands for no known
    # period, which fits no timer handle.
    period_map: dict[tuple[str, str], int] = {}
    for node_name, node_info in graph.nodes.items():
        node_info = apply_timer_period_overrides(node_name, node_info, timer_period_overrides)
        for t in node_info.timers:
            period_map[(node_name, t.callback)] = period_ms_to_ns(t.period_ms) or 0

    # Creation order lookup:
    # (node_class, kind family, callback_name) -> (creation index, group index)
    creation_map: dict[tuple[str, str, str], tuple[int, int]] = {}
    reliability_map: dict[tuple[str, str], str] = {}
    for node_info in graph.nodes.values():
        user_groups = [g.name for g in node_info.callback_groups if g.name != "default_group"]
        for family, entities in (("timer", node_info.timers), ("sub", node_info.subscribers)):
            for index, entity in enumerate(entities):
                group = entity.callback_group
                if getattr(entity, "tf2_listener", None):
                    # An input of the admitted TransformListener.
                    # Its group belongs to tf2_ros's own executor until the
                    # binding detaches it (kGroupTf2Listener).
                    group_index = -4
                elif group in (None, "default_group"):
                    group_index = -1
                elif group in user_groups:
                    group_index = user_groups.index(group)
                else:
                    group_index = -2
                creation_map.setdefault(
                    (node_info.class_name, family, entity.callback), (index, group_index))
        # Subscriptions sharing one callback cannot be told apart
        # by RID, so they carry the weakest reliability any of them has.
        for s in node_info.subscribers:
            key = (node_info.class_name, s.callback)
            rel = s.qos_reliability or ""
            if key not in reliability_map or rel == "best_effort":
                reliability_map[key] = rel

    def creation_index(class_name: str, kind: str, cb_name: str) -> tuple[int, int]:
        family = "sub" if kind == "sub" else "timer" if kind in _TIMER_KINDS else None
        if family is None:
            return -1, -2
        return creation_map.get((class_name, family, cb_name), (-1, -2))

    def sub_reliability(class_name: str, kind: str, cb_name: str) -> str:
        return reliability_map.get((class_name, cb_name), "") if kind == "sub" else ""

    table: list[tuple[int, str, str, str, str, int, int, int, str]] = []
    seen: set[str] = set()

    for node_name, node_info in graph.nodes.items():
        binding_key = binding_keys[node_name]
        reactor_class = class_name_to_reactor_name(binding_key)
        if reactor_class in seen:
            continue
        seen.add(reactor_class)

        reactor = class_to_reactor.get(reactor_class)
        if reactor is None:
            continue

        for reaction in reactor.reactions:
            if reaction.reaction_id < 0:
                continue
            topic = _infer_topic(reaction)
            cb_name = _cb_name_from_body(reaction, binding_key)
            period_ns = period_map.get((node_name, cb_name), 0)
            table.append((
                reaction.reaction_id,
                binding_key,
                cb_name,
                reaction.kind,
                topic,
                period_ns,
                *creation_index(node_info.class_name, reaction.kind, cb_name),
                sub_reliability(node_info.class_name, reaction.kind, cb_name),
            ))

        # Sub-reactors
        for inst in reactor.instances:
            sub = class_to_reactor.get(inst.reactor_class)
            if sub is None or inst.reactor_class in seen:
                continue
            seen.add(inst.reactor_class)
            for reaction in sub.reactions:
                if reaction.reaction_id < 0:
                    continue
                topic = _infer_topic(reaction)
                cb_name = _cb_name_from_body(reaction, binding_key)
                period_ns = period_map.get((node_name, cb_name), 0)
                table.append((
                    reaction.reaction_id,
                    binding_key,
                    cb_name,
                    reaction.kind,
                    topic,
                    period_ns,
                    *creation_index(node_info.class_name, reaction.kind, cb_name),
                    sub_reliability(node_info.class_name, reaction.kind, cb_name),
                ))

    table.sort(key=lambda row: row[0])
    return table


_CORR_ROLE_ENUM = {
    "local": "ros2_lf_binding::CorrEdgeRole::kLocal",
    "egress": "ros2_lf_binding::CorrEdgeRole::kEgress",
    "ingress": "ros2_lf_binding::CorrEdgeRole::kIngress",
}


def _corr_role_fields(e) -> str:
    """Role, global id and peer node of a federated edge's spec.

    Empty for an unfederated edge, whose spec keeps the defaults.
    An analyzed subscription reliability follows them, so an unfederated edge
    then spells out the role defaults. An analyzed depth follows
    the reliability. ``true`` follows them for a lifecycle
    publisher, which the binding binds whenever the node creates it.
    A second ``true`` follows for a lifecycle subscription made or
    reset in a hook (``sub_rebind``), the first then spelled out.
    """
    reliability = getattr(e, "sub_reliability", "") or ""
    depth = getattr(e, "sub_depth", None)
    sub_rebind = getattr(e, "sub_rebind", False)
    rebind = getattr(e, "pub_rebind", False) or sub_rebind
    if getattr(e, "federate", None) is None:
        if not reliability and depth is None and not rebind:
            return ""
        role = f", {_CORR_ROLE_ENUM['local']}, -1, \"\""
    else:
        role = f", {_CORR_ROLE_ENUM[e.role]}, {e.global_id}, \"{e.peer_node}\""
    if reliability or depth is not None or rebind:
        role += f", \"{reliability}\""
    if depth is not None or rebind:
        role += f", {-1 if depth is None else depth}"
    if rebind:  # a lifecycle publisher, bound when created
        role += ", true" if getattr(e, "pub_rebind", False) else ", false"
    if sub_rebind:  # a lifecycle reader, admitted when created
        role += ", true"
    return role


def collect_publisher_qos(
    graph,  # SystemGraph
    binding_keys: dict[str, str] | None = None,
) -> list[tuple[str, str, str]]:
    """``(binding_key, topic, analyzed reliability)`` per analyzed publisher.

    The binding logs RCLLF-H000 at startup for a publisher whose
    reliability the analysis did not see (empty third column), with the
    effective one. Every publisher gets a row, also one on no edge, and a known
    value is kept so that twin publishers of one node on one topic can be
    counted. A publisher without a static topic name cannot be matched to a
    handle and gets no row.
    """
    from colcon_lf.generation.binding_key import build_binding_keys

    if binding_keys is None:
        binding_keys = build_binding_keys(graph.nodes)
    rows: list[tuple[str, str, str]] = []
    for node_key, node_info in graph.nodes.items():
        key = binding_keys.get(node_key, node_info.class_name)
        for p in node_info.publishers:
            if p.topic and not p.topic_dynamic:
                rows.append((key, p.topic, p.qos_reliability or ""))
    return rows


def emit_rid_init_cpp(
    rid_table: list[tuple[int, str, str, str, str, int, int, int, str]],
    pkg_name: str,
    corr_edges=None,  # list[CorrEdge] | None
    foreign_executor_acks: list[tuple[str, str]] | None = None,
    legacy_ingress=None,
    tf2_configs: list[tuple[str, int, str]] | None = None,  # list[CorrEdge] | None
    publisher_qos: list[tuple[str, str, str]] | None = None,
    lf_system=None,  # LFSystem | None
) -> str:
    """Emit a C++ source file that registers all RID entries at startup.

    Called from main.cpp before ros2_lf_runtime_init() so that
    ros2_lf_bind_node() can match ROS2 handles to reaction IDs.

    With *corr_edges* it also registers every topic edge of the
    correspondence table: admitted edges with both RIDs, the delay and the
    schedule-derived bounds (take timeout, worker lag bound,
    burst, retention, carrier), legacy edges with their reason.

    With *foreign_executor_acks*, a list of ``(node_class, code)``
    pairs, it tells the binding which nodes acknowledged a hazard that covers
    handles spun by an executor of their own (RCLLF-R002, tf2_ros). Only such
    a node may keep handles without a reaction ID, and only when their callback
    group already belongs to another executor at bind time.

    With *legacy_ingress*, the refused cross-federate edges read
    in this federate, it registers each as an ingress copy, which the binding
    uses only for the startup QoS check of its reader.

    With *publisher_qos* (rows of :func:`collect_publisher_qos`) it
    registers the analyzed reliability of every publisher, which the binding
    compares at startup to log RCLLF-H000 where the analysis saw none.

    With *lf_system* it registers the carrier of every system
    link and the offsets of the reaction-triggering input ports in lfc's self
    structs (:mod:`colcon_lf.generation.readback_links`); the file then
    includes lfc's class headers and must be compiled in lfc's target.
    """
    from colcon_lf.generation.readback_links import emit_cpp as emit_link_cpp

    link_includes, link_lines = emit_link_cpp(lf_system)
    lines: list[str] = [
        "// Auto-generated by colcon lf-generate. DO NOT EDIT.",
        "// Copyright 2024 rcllf Contributors",
        "// SPDX-License-Identifier: Apache-2.0",
        '#include "ros2_lf_reaction_ids.h"',
        '#include "ros2_lf_binding/ros2_lf_binding_internal.h"',
    ] + (
        ['#include "ros2_lf_binding/corr_table_api.h"'] if corr_edges or legacy_ingress or publisher_qos else []
    ) + link_includes + [
        "",
        "void ros2_lf_reaction_ids_init() {",
        f"  ros2_lf_binding::resize_handle_table({len(rid_table)});",
    ]

    for rid, node_class, cb_name, kind, topic, period_ns, *rest in rid_table:
        index = rest[0] if rest else -1
        group = rest[1] if len(rest) > 1 else -2
        # The analyzed reliability of a subscription, when known.
        reliability = f', "{rest[2]}"' if len(rest) > 2 and rest[2] else ""
        macro = _rid_macro(node_class, cb_name)
        escaped_class = node_class.replace('"', '\\"')
        escaped_cb = cb_name.replace('"', '\\"')
        escaped_topic = topic.replace('"', '\\"')
        lines.append(
            f'  ros2_lf_binding::register_rid_entry({{'
            f'{macro}, "{escaped_class}", "{escaped_cb}", '
            f'"{kind}", "{escaped_topic}", {period_ns}LL, {index}, {group}{reliability}'
            f'}});'
        )

    def q(text: str) -> str:
        return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'

    def legacy_row(fn: str, e) -> str:
        # With a resolved node-local subscription (or ambiguous
        # twins) the row also carries the analyzed reliability and depth
        # (-1: no value), which the binding compares with the reader's
        # actual QoS at startup. An empty topic means the graph topic.
        qos = ""
        if e.sub_topic or e.sub_reliability or e.sub_depth is not None:
            depth = -1 if e.sub_depth is None else e.sub_depth
            qos = f", {q(e.sub_topic)}, {q(e.sub_reliability or '')}, {depth}"
        return (
            f"  ros2_lf_binding::{fn}({q(e.topic)}, "
            f"{q(e.pub_key)}, {q(e.sub_key)}, {q(e.reason or '')}{qos});"
        )

    for node_class, code in foreign_executor_acks or []:
        lines.append(
            f"  ros2_lf_binding::register_foreign_executor_ack({q(node_class)}, {q(code)});"
        )
    # execution.yaml nodes.<node>.tf2 over the adapter literals.
    for node_class, bound_ns, on_timeout in tf2_configs or []:
        lines.append(
            f"  ros2_lf_binding::register_tf2_config({q(node_class)}, {int(bound_ns)}LL, "
            f"{q(on_timeout)});"
        )

    # A fan-in group of two or more admitted edges registers its
    # members' lead and rank; a group of one has no call (byte-identical).
    group_size = Counter(
        e.group_lead for e in corr_edges or []
        if e.edge_id is not None and getattr(e, "group_lead", None) is not None
    )
    for e in corr_edges or []:
        if e.edge_id is not None:
            lines.append(
                f"  ros2_lf_binding::register_corr_edge({{{e.edge_id}, {q(e.pub_key)}, "
                f"{{{', '.join(str(r) for r in e.pub_rids)}}}, {q(e.pub_topic)}, {q(e.sub_key)}, {e.sub_rid}, "
                f"{q(e.sub_topic)}, {e.delay_ns}LL, {e.timeout_ns}LL, {e.max_lag_ns}LL, "
                f"{e.burst}u, {e.retain}u, {e.carrier}u, {e.reader_depth}u"
                + _corr_role_fields(e) + "});"
            )
            if getattr(e, "deferred", False):
                # The subscriber's drain joins at the cutoff tag.
                if e.role == "egress":
                    raise ValueError(
                        f"correspondence: egress edge {e.label()} is marked 'join: deferred', "
                        f"the join belongs to the subscriber's ingress row")
                lines.append(f"  ros2_lf_binding::set_corr_edge_deferred({e.edge_id});")
            if getattr(e, "same_tag", False):
                # The drain runs the first record at its publication tag.
                lines.append(f"  ros2_lf_binding::set_corr_edge_same_tag({e.edge_id});")
            if getattr(e, "tardy_drop", False):
                # A late record on a decentralized link is lost, not fatal.
                lines.append(f"  ros2_lf_binding::set_corr_edge_tardy_drop({e.edge_id});")
            if getattr(e, "control_stop", False) and e.role == "ingress":
                # A missing COMPLETE record stops LF, not only reports.
                lines.append(f"  ros2_lf_binding::set_corr_edge_control_stop({e.edge_id});")
            lead = getattr(e, "group_lead", None)
            if lead is not None and group_size[lead] > 1:
                lines.append(
                    f"  ros2_lf_binding::set_corr_edge_fan_in({e.edge_id}, {lead}, "
                    f"{e.fan_in_rank}u);"
                )
        else:
            lines.append(legacy_row("register_corr_legacy_edge", e))
    for e in legacy_ingress or []:
        lines.append(legacy_row("register_corr_legacy_ingress", e))
    for key, topic, reliability in publisher_qos or []:
        lines.append(
            f"  ros2_lf_binding::register_publisher_qos({q(key)}, {q(topic)}, {q(reliability)});"
        )
    lines += _min_input_period_lines(corr_edges, rid_table, q)

    lines += link_lines
    lines += ["}", ""]
    return "\n".join(lines) + "\n"


def _min_input_period_lines(corr_edges, rid_table, q) -> list[str]:
    """Register every declared ``min_input_period_ms`` that sized a bound.

    The sizing records each declaration it used in an edge's
    ``bound_inputs["min_input_periods_ns"]``, keyed ``"<node key>:<topic>"``
    with the launch-level node key. The binding knows a node by its binding
    key, which the edges carry next to the node key (``pub_node``/``pub_key``,
    ``sub_node``/``sub_key``). The binding counts and reports every run of the
    subscription callback closer than the period, which would overflow the
    bounds sized from it. A declaration of a node in this RID table whose
    subscription has no row cannot be checked, so it refuses generation rather
    than go unchecked. A node with no row at all runs in another federate.
    """
    declared: dict[str, int] = {}
    node_to_key: dict[str, str] = {}
    for e in corr_edges or []:
        for node, key in ((e.pub_node, e.pub_key), (e.sub_node, e.sub_key)):
            if node and key:
                node_to_key[node] = key
        for label, ns in (
                (getattr(e, "bound_inputs", None) or {}).get("min_input_periods_ns", {}).items()):
            # One declaration per (node, topic) in execution.yaml, so every
            # edge records the same value. Two values could not both be checked.
            if declared.setdefault(label, ns) != ns:
                raise ValueError(
                    f"min_input_period_ms of {label}: edges recorded {declared[label]} ns "
                    f"and {ns} ns, the binding checks one period per input")
    subs = {(row[1], row[4]) for row in rid_table if row[3] == "sub"}
    # A federate's RID table holds its own nodes only. A declaration of a node
    # that runs in another federate is registered by that federate's table.
    local = {row[1] for row in rid_table}
    out: list[str] = []
    for label in sorted(declared):
        match = [(n, k) for n, k in node_to_key.items() if label.startswith(f"{n}:")]
        if len(match) != 1:
            raise ValueError(
                f"min_input_period_ms of {label}: no single node with a binding key "
                f"matches it")
        node, key = match[0]
        topic = label[len(node) + 1:]
        if key not in local:
            continue
        if (key, topic) not in subs:
            raise ValueError(
                f"min_input_period_ms of {label}: the RID table has no subscription of "
                f"'{key}' to '{topic}', so the binding could not check it")
        out.append(
            f"  ros2_lf_binding::register_min_input_period({q(key)}, {q(topic)}, "
            f"{int(declared[label])}LL);"
        )
    return out


def _infer_topic(reaction) -> str:
    """Extract topic, service, or action name from reaction body, or "" for timers."""
    import re
    # Subscription: ros2_lf_invoke_sub(self, RID, "topic") or ros2_lf_invoke_sub_n (P17e)
    m = re.search(r'ros2_lf_invoke_sub(?:_n)?\([^,]+,\s*[^,]+,\s*"([^"]*)"', reaction.body)
    if m:
        return m.group(1)
    # External subscription: the topic rides in a trailing comment.
    m = re.search(
        r'ros2_lf_invoke_external_sub\(.*/\* external topic "([^"]*)" \*/', reaction.body,
    )
    if m:
        return m.group(1)
    # Correspondence drain: ros2_lf_corr_drain(self, E, RID, "topic")
    m = re.search(
        r'ros2_lf_corr_drain\([^,]+,\s*[^,]+,\s*[^,]+,\s*"([^"]*)"', reaction.body,
    )
    if m:
        return m.group(1)
    # Service send/server/client_cb: last string arg is the service name
    m = re.search(
        r'ros2_lf_invoke_srv_(?:send|server|client_cb)\([^,]+,\s*[^,]+,\s*"([^"]*)"',
        reaction.body,
    )
    if m:
        return m.group(1)
    # Action goal_send/goal_server/client_cb/cancel_server/result_server: the
    # third argument is the action name.
    m = re.search(
        r'ros2_lf_invoke_action_(?:goal_send|goal_server|client_cb|cancel_server|result_server)\('
        r'[^,]+,\s*[^,]+,\s*"([^"]*)"',
        reaction.body,
    )
    if m:
        return m.group(1)
    return ""


def _cb_name_from_body(reaction, binding_key: str | None = None) -> str:
    """Extract callback name from the RID macro in the reaction body.

    The macro is ``RID_{sanitize(binding_key)}_{sanitize(callback)}``.  When the
    binding key is known (always, in the generator), strip exactly that prefix —
    a synthesized key contains ``__`` and arbitrarily many ``_``, so the legacy
    "split after the second ``_``" heuristic is only correct for plain class
    names.  The heuristic is kept as the fallback for callers with no key.
    """
    import re
    rid_name = getattr(reaction, "rid_name", None)
    if rid_name:
        return rid_name
    m = re.search(r'ros2_lf_invoke_\w+\(self,\s*(RID_\w+)', reaction.body)
    if not m:
        return "unknown"
    macro = m.group(1)
    if binding_key:
        prefix = f"RID_{sanitize_lf_identifier(binding_key)}_"
        if macro.startswith(prefix):
            return macro[len(prefix):]
    # RID_{class}_{callback} → split after second _
    parts = macro.split("_", 2)
    return parts[2] if len(parts) > 2 else macro


def collect_foreign_executor_acks(
    resolved_model, acknowledged_hazards, graph, binding_keys=None
) -> list[tuple[str, str]]:
    """``(binding_key, code)`` for every node whose RCLLF-R002 record (tf2_ros or
    take, a mechanism that may spin handles on an executor of its own) is
    unresolved and acknowledged in execution.yaml.

    The key is the node's binding key, as in the RID table: the binding looks
    the acknowledgement up by it, and a class with two instances binds as
    ``Class__a`` and ``Class__b``, not as ``Class``."""
    from colcon_lf.generation.binding_key import build_binding_keys
    from colcon_lf.resolved_model.model import PROVENANCE_UNRESOLVED

    if resolved_model is None or "RCLLF-R002" not in (acknowledged_hazards or set()):
        return []
    if binding_keys is None:
        binding_keys = build_binding_keys(graph.nodes)
    acks: set[tuple[str, str]] = set()
    for record in resolved_model.records:
        if record.provenance != PROVENANCE_UNRESOLVED or record.reason != "RCLLF-R002":
            continue
        node_key = record.subject.get("node")
        if node_key in graph.nodes:
            acks.add((binding_keys.get(node_key, graph.nodes[node_key].class_name), "RCLLF-R002"))
    return sorted(acks)


def collect_tf2_configs(resolved_model, graph, binding_keys=None) -> list[tuple[str, int, str]]:
    """``(binding_key, wait_bound_ns or 0, on_timeout or "")`` per node whose
    ``tf2.lookup`` records execution.yaml configured. The binding
    hands them to every rcllf_tf2::AcquisitionLookup the node constructs."""
    from colcon_lf.generation.binding_key import build_binding_keys
    from colcon_lf.resolved_model.model import PROVENANCE_EXPLICITLY_CONFIGURED

    if resolved_model is None:
        return []
    if binding_keys is None:
        binding_keys = build_binding_keys(graph.nodes)
    out: dict[str, tuple[str, int, str]] = {}
    for r in resolved_model.records:
        if (r.provenance != PROVENANCE_EXPLICITLY_CONFIGURED
                or not r.property.startswith("tf2.lookup.")):
            continue
        node_key = r.subject.get("node")
        if node_key not in graph.nodes:
            continue
        keys = r.value.get("configured", [])
        bound = r.value["wait_bound_ns"] if "wait_bound_ns" in keys else 0
        on_timeout = r.value["on_timeout"] if "on_timeout" in keys else ""
        key = binding_keys.get(node_key, graph.nodes[node_key].class_name)
        out[key] = (key, bound or 0, on_timeout or "")
    return sorted(out.values())
