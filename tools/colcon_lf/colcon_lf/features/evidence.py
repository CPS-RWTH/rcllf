def problems(registry_ids: set[str]) -> list[str]:
    """Every disagreement between this mapping, the registry and the stated limits."""
    out: list[str] = list(_limits.problems())
    for fid in sorted(registry_ids - EVIDENCE.keys()):
        out.append(f"feature '{fid}' is in REGISTRY but has no evidence class in evidence.py")
    for fid in sorted(EVIDENCE.keys() - registry_ids):
        out.append(f"feature '{fid}' has an evidence class but is not in REGISTRY")
    for fid, (_, limits) in sorted(EVIDENCE.items()):
        for slug in limits:
            if slug not in LIMIT_IDS:
                out.append(
                    f"feature '{fid}' cites limit '{slug}', which is not in "
                    "colcon_lf/features/limits.py"
                )
    return out
