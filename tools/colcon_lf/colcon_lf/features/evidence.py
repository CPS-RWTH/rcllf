"""Evidence class and stated limits per registered feature.

The registry says what the generator does with a feature. This module says how
far the evaluation evidence reaches for it, in four classes, and which stated
limits bound it. The limits are those of ``colcon_lf.features.limits``.
``docs_table`` renders both into ``docs/features/support-matrix.md``, and
``docs_table --check`` fails when this mapping and ``REGISTRY`` cover different
feature ids, when a feature cites a limit slug that ``limits`` does not hold, or
when a limit row cannot be rendered.
"""

from __future__ import annotations

import enum

from colcon_lf.features import limits as _limits


class Evidence(enum.Enum):
    """How far the evaluation evidence reaches for one feature."""

    VALIDATED = "validated"
    EXPERIMENTAL = "experimental"
    REFUSED = "refused"
    UNRESOLVED = "unresolved"


EVIDENCE_MEANING = {
    Evidence.VALIDATED: (
        "exercised by a system whose evaluation runs report the feature as supported "
        "(complete, covered and reconciled traces). The evaluation systems and their "
        "run data are described in the rcllf paper and are not part of this "
        "repository"
    ),
    Evidence.EXPERIMENTAL: (
        "analyzed and generated by the playground, with no evaluation row behind it. "
        "Some of these examples also run in the CI runtime smoke tests"
    ),
    Evidence.REFUSED: "generation refuses the input with an error diagnostic",
    Evidence.UNRESOLVED: (
        "the analyser reports it, and the runtime behavior is not determined by "
        "the generated program (a warning or an unresolved value)"
    ),
}

# Limit id (L1, L2, ...) to its statement, from ``colcon_lf.features.limits``. The ids
# are derived from the row order, so the mapping below cites limits by slug.
LIMITS: dict[str, str] = _limits.limits()
LIMIT_IDS: dict[str, str] = _limits.limit_ids()

