"""Generate ``docs/features/support-matrix.md`` from the feature ``REGISTRY``.

Hand-written support claims could drift from the registry silently; this
generator makes the table a mechanical projection of
``REGISTRY``, the same source of truth the playground CI harness
asserts against, so a claim about what is supported can never diverge from
what the registry actually declares.

Run as a script::

    python3 -m colcon_lf.features.docs_table              # writes docs/features/support-matrix.md
    python3 -m colcon_lf.features.docs_table --out FILE    # writes FILE instead
    python3 -m colcon_lf.features.docs_table --check       # exit 1 if the committed
                                                           # file is stale (no write)

``--check`` is what CI uses (the drift step): it re-renders the table
in memory and diffs it against the committed file without touching a dirty
workspace, then prints a unified diff and exits 1 on mismatch.
"""

from __future__ import annotations

import argparse
import difflib
import sys
from pathlib import Path

from colcon_lf.features.diagnostics import Severity, Support
from colcon_lf.features.evidence import (
    EVIDENCE,
    EVIDENCE_MEANING,
    LIMIT_IDS,
    LIMITS,
    Evidence,
    problems,
)
from colcon_lf.features.registry import REGISTRY, FeatureModule

HEADER_MARKER = (
    "<!-- GENERATED by python3 -m colcon_lf.features.docs_table, do not edit by hand -->"
)

# Which RMW the binding runs on. Source: the startup gate in
# packages/lf-frame/ros2_lf_binding/src/corr_runtime.cpp (refuses any identifier
# but rmw_fastrtps_cpp).
MIDDLEWARE_STATEMENT = (
    "**Middleware.** rcllf requires Fast DDS (`rmw_fastrtps_cpp`, the RMW the "
    "container sets): the binding keys every received sample by its publisher GID "
    "and publication sequence number, and a program with an admitted correspondence "
    "edge refuses any other RMW at startup. Cyclone "
    "DDS does not report the publication sequence number. Zenoh (`rmw_zenoh_cpp`) "
    "is untested."
)

# Which deployments the release supports. Source: the supported scope in README.md
# and CHANGELOG.md, and the federated runtime-smoke entries in .github/workflows/ci.yml.
DEPLOYMENT_STATEMENT = (
    "**Deployment.** Every node of a launch file in one process, and one process per "
    "node (`--federate per-node`) under centralized coordination, are supported. "
    "Per-process partitions, a custom federation YAML, federation across hosts and "
    "decentralized coordination are experimental; see [Federation](federation.md)."
)

_SUPPORT_BADGE = {
    Support.SUPPORTED: "Supported",
    Support.WARN: "Warns",
    Support.REJECT: "Rejected",
    Support.STUB: "Stub",
}

_OUTCOME_TEXT = {
    "pass": "pass",
    "warn": "warn",
    "reject": "reject",
}

_DEFAULT_OUT = (
    Path(__file__).resolve().parents[4] / "docs" / "features" / "support-matrix.md"
)


def _severity_text(module: FeatureModule, code: str) -> str:
    severity: Severity = module.severity[code]
    return f"{code} ({severity.value})"


def _codes_cell(module: FeatureModule) -> str:
    if not module.codes:
        return "none"
    return ", ".join(_severity_text(module, code) for code in module.codes)


def _example_cell(module: FeatureModule) -> str:
    if module.playground is None:
        return "none"
    return f"`{module.playground.example}`"


def _outcome_cell(module: FeatureModule) -> str:
    if module.playground is None:
        return "none"
    return _OUTCOME_TEXT[module.playground.expected_outcome.value]


def _notes_cell(module: FeatureModule) -> str:
    return module.docs_entry


def _limits_cell(module: FeatureModule) -> str:
    limits = EVIDENCE[module.feature_id][1]
    ids = [LIMIT_IDS[slug] for slug in limits]
    return ", ".join(f"[{lid}](#{lid.lower()})" for lid in ids) if ids else "none"


def _table_row(module: FeatureModule) -> str:
    cells = [
        module.title,
        _SUPPORT_BADGE[module.support],
        EVIDENCE[module.feature_id][0].value,
        _limits_cell(module),
        _codes_cell(module),
        _example_cell(module),
        _outcome_cell(module),
        _notes_cell(module),
    ]
    escaped = [cell.replace("|", "\\|") for cell in cells]
    return "| " + " | ".join(escaped) + " |"


def render() -> str:
    """Render the full Markdown page from ``REGISTRY``. Deterministic: sorted by feature_id."""
    lines: list[str] = []
    lines.append(HEADER_MARKER)
    lines.append("")
    lines.append("# Support Matrix")
    lines.append("")
    lines.append(
        "This table is generated from the feature registry "
        "(`tools/colcon_lf/colcon_lf/features/registry.py`) by "
        "`python3 -m colcon_lf.features.docs_table`. Every row corresponds to one "
        "registered `FeatureModule`. Every playground example listed here is "
        "analyzed and generated in CI and asserted to produce the stated outcome (see "
        "`tools/colcon_lf/tests/playground/`). Because the table is regenerated "
        "and drift-checked in CI, a support claim on this page cannot go stale "
        "the way a hand-written one could. The registry's diagnostic codes are "
        "the static-analysis half of the soundness story, and the "
        "[Soundness Checker](soundness.md) checks the runtime half by tracing a "
        "real run and diffing it against the extracted model."
    )
    lines.append("")
    lines.append(MIDDLEWARE_STATEMENT)
    lines.append("")
    lines.append(DEPLOYMENT_STATEMENT)
    lines.append("")
    lines.append(
        "The Evidence column says how far the evaluation evidence reaches for each "
        "feature. It comes from `tools/colcon_lf/colcon_lf/features/evidence.py`, "
        "and the drift check fails when that file and the registry cover different "
        "features. The classes are these."
    )
    lines.append("")
    for evidence in Evidence:
        lines.append(f"- **{evidence.value}**: {EVIDENCE_MEANING[evidence]}.")
    lines.append("")
    lines.append(
        "| Feature | Support | Evidence | Limits | Diagnostic codes | Playground example "
        "| Expected outcome | Notes |"
    )
    lines.append("|---|---|---|---|---|---|---|---|")
    for feature_id in sorted(REGISTRY):
        lines.append(_table_row(REGISTRY[feature_id]))
    lines.append("")
    lines.append("## Stated limits")
    lines.append("")
    lines.append(
        f"These are the stated limits L1 to {list(LIMITS)[-1]}. Each one bounds the "
        "features that cite it in the Limits column. They come from "
        "`tools/colcon_lf/colcon_lf/features/limits.py`, and the drift check fails "
        "when a feature cites a limit that file does not hold."
    )
    lines.append("")
    lines.append("| Limit | Statement |")
    lines.append("|---|---|")
    for lid, text in LIMITS.items():
        anchor = f'<a id="{lid.lower()}"></a>'
        lines.append(f"| {anchor}{lid} | {text} |")
    lines.append("")
    return "\n".join(lines)


def _diff(expected: str, actual: str, path: Path) -> str:
    return "".join(
        difflib.unified_diff(
            actual.splitlines(keepends=True),
            expected.splitlines(keepends=True),
            fromfile=f"{path} (committed)",
            tofile=f"{path} (generated)",
        )
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out",
        type=Path,
        default=_DEFAULT_OUT,
        help="Output path (default: docs/features/support-matrix.md relative to repo root).",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Do not write; exit 1 with a diff if the file at --out is stale.",
    )
    args = parser.parse_args(argv)

    if args.check:
        found = problems(set(REGISTRY))
        if found:
            for problem in found:
                print(f"error: {problem}")
            return 1

    generated = render()

    if args.check:
        if not args.out.exists():
            print(f"error: {args.out} does not exist. Run without --check to generate it.")
            return 1
        committed = args.out.read_text()
        if committed != generated:
            print(f"error: {args.out} is stale (regenerate with docs_table.py):\n")
            print(_diff(generated, committed, args.out))
            return 1
        print(f"{args.out} is up to date.")
        return 0

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(generated)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
