"""The analyzed reliability of every publisher reaches the binding.

The binding logs RCLLF-H000 at startup for a publisher whose reliability the
analysis did not see, naming the effective one. It needs one row per analyzed
publisher in the generated RID init source, also for a publisher on no edge,
with the analyzed value so that twin publishers on one topic can be counted.
"""

from __future__ import annotations

import dataclasses
import json

from colcon_lf.generation.lf_emitter import emit_lf_system
from colcon_lf.generation.lf_generator import generate_lf_system
from colcon_lf.node_analysis.models import CallbackInfo, PublisherInfo
from colcon_lf.verb.generate import _emit_lfc_artifacts
from .test_correspondence_emission import MSG, _graph, _pub, _sub, _tc
from .test_xfed_correspondence import _federate


def _row(key: str, topic: str, reliability: str) -> str:
    return f'ros2_lf_binding::register_publisher_qos("{key}", "{topic}", "{reliability}");'


def _nodes():
    # PubNode: "data" read by SubNode with no analyzed reliability, "known" on
    # no edge analyzed reliable, "loose" on no edge with no analyzed value.
    pub = _pub("pub", "PubNode", callbacks=[
        CallbackInfo(name="tick", publishers_used=["data", "known", "loose"])])
    pub.publishers += [
        PublisherInfo(topic="known", message_type=MSG, qos_reliability="reliable"),
        PublisherInfo(topic="loose", message_type=MSG),
    ]
    return [pub, _sub("sub", "SubNode")]


def test_single_process_init_registers_every_publisher_with_its_analyzed_reliability(tmp_path):
    src = tmp_path / "packages/src/test_pkg/src"
    src.mkdir(parents=True)
    nodes = []
    for n in _nodes():
        (src / f"{n.name}.cpp").write_text("// generated by the test\n")
        nodes.append(dataclasses.replace(n, source_file=str(src / f"{n.name}.cpp")))
    graph = _graph(nodes, [_tc("/data", ["pub"], ["sub"])])
    sj = tmp_path / "lf-analysis/test_pkg/bringup/system.json"
    sj.parent.mkdir(parents=True)
    sj.write_text(json.dumps({"name": "bringup", "nodes": {}, "communication": {"topics": []}}))
    lf_system = generate_lf_system(graph, target_lfc=True)
    out_dir = sj.parent / "lf"
    out_dir.mkdir()
    (out_dir / f"{lf_system.name}.lf").write_text(emit_lf_system(lf_system))
    pkg = _emit_lfc_artifacts(system_json=sj, out_dir=out_dir, lf_system=lf_system, graph=graph)
    init = (tmp_path / "lf-generated" / pkg / "src/ros2_lf_reaction_ids_init.cpp").read_text()
    for want in (_row("PubNode", "data", ""), _row("PubNode", "known", "reliable"),
                 _row("PubNode", "loose", "")):
        assert want in init, (
            f"no analyzed publisher reliability row {want!r}, so the binding cannot log "
            f"RCLLF-H000 for that publisher at startup:\n{init}")
    assert '#include "ros2_lf_binding/corr_table_api.h"' in init
    assert "register_publisher_qos(\"SubNode\"" not in init, "SubNode publishes nothing"


def test_each_federate_registers_only_its_own_publishers(tmp_path):
    out = _federate(tmp_path, _nodes(), [_tc("/data", ["pub"], ["sub"])],
                    {"pub": "pub", "sub": "sub"})
    want = _row("PubNode", "loose", "")
    assert want in out["pub"]["init"], (
        f"no analyzed publisher reliability row {want!r} in the publisher's federate, so "
        f"its binding cannot log RCLLF-H000 at startup:\n{out['pub']['init']}")
    assert "register_publisher_qos" not in out["sub"]["init"], out["sub"]["init"]


def test_a_publisher_without_a_static_topic_gets_no_row(tmp_path):
    from colcon_lf.generation.binding_header_emitter import collect_publisher_qos

    nodes = _nodes()
    nodes[0].publishers.append(
        PublisherInfo(topic="", message_type=MSG, topic_dynamic=True))
    rows = collect_publisher_qos(_graph(nodes, []))
    assert rows == [("PubNode", "data", ""), ("PubNode", "known", "reliable"),
                    ("PubNode", "loose", "")], rows
