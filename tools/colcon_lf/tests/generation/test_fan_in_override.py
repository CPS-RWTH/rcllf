"""The after override of the k-th stub fan-in writer applies.

Two publisher nodes on one topic into one subscriber share one merged stub
input; route_fan_in moves the k-th writer's link to port ``<port>_fanin_k``.
The cross-federate override lookup used that moved name, so the override of
writer k >= 1 matched nothing and the link silently ran the 5 msec default
(probe P17g finding S2). The link now records the subscriber's own port
(``user_destination``), which the override, the STP lookup and the resolved
model's provenance use.
"""

from __future__ import annotations

import dataclasses
import json
from pathlib import Path

import pytest

from colcon_lf.federation.partition import AfterOverride, FederationMap
from colcon_lf.verb import generate as gen
from ..corr_declared import declared
from .test_correspondence_emission import _graph, _pub, _sub, _tc
from .test_xfed_correspondence import FED

TOGETHER = {"pa": "pubs", "pb": "pubs", "sub": "sub"}


def _generate(tmp_path: Path, node_fed, overrides=(), coordination="centralized",
              monkeypatch=None):
    """Run the real federated generator, return (rc, cross_links rows)."""
    src = tmp_path / "packages/src/test_pkg/src"
    src.mkdir(parents=True, exist_ok=True)
    nodes = []
    for n in [_pub("pa", "PubA"), _pub("pb", "PubB"), _sub("sub", "SubNode")]:
        f = src / f"{n.name}.cpp"
        f.write_text("// generated by the test\n")
        nodes.append(dataclasses.replace(n, source_file=str(f)))
    graph = _graph(nodes, [_tc("/data", ["pa", "pb"], ["sub"])])
    adir = tmp_path / "lf-analysis/test_pkg/bringup"
    adir.mkdir(parents=True, exist_ok=True)
    sj = adir / "system.json"
    sj.write_text(json.dumps({"name": "bringup", "nodes": {}, "communication": {"topics": []}}))
    fmap = FederationMap(node_to_federate=dict(node_fed),
                         federate_names=list(dict.fromkeys(node_fed.values())),
                         after_overrides=list(overrides), coordination=coordination)
    links: list = []
    if monkeypatch is not None:
        monkeypatch.setattr(gen, "_stage_federated_resolved_model",
                            lambda _sj, cross_links: links.extend(cross_links))
    rc = gen._generate_federated(system_json=sj, graph=graph, fmap=fmap, after_delay="0 msec",
                                 generate_launch=False, corr_bounds=declared(graph, 1))
    return rc, links


def _top(tmp_path: Path) -> str:
    return (tmp_path / "lf-generated" / FED / "lf/Bringup_federated.lf").read_text()


@pytest.mark.parametrize("coordination", ["centralized", "decentralized"])
def test_override_of_second_writer_applies_and_is_cited(tmp_path, monkeypatch, coordination):
    # d = 0 is admitted, so the legacy stub fan-in this test reads
    # needs a refused edge: 1 ns under the flush is refused (xfed_flush_min).
    monkeypatch.setenv("RCLLF_XFED_FLUSH", "1")
    overrides = [AfterOverride("pa.data", "sub.data", 1),
                 AfterOverride("pb.data", "sub.data", 1)]
    rc, links = _generate(tmp_path, TOGETHER, overrides, coordination, monkeypatch)
    assert rc == 0
    # Before the P17g fix pb's link silently ran the default delay.
    assert "pubs.pb_data -> sub.data_fanin_1 after 1 nsec" in _top(tmp_path), _top(tmp_path)
    pb = [r for r in links if r["src"] == "pb"]
    assert len(pb) == 1 and pb[0]["after_ns"] == 1, links
    # The k >= 1 link cites the override it runs, not the extracted default.
    assert "after_overrides pb.data -> sub.data" in pb[0]["evidence"], pb[0]


def test_misspelled_override_of_second_writer_is_unmatched(tmp_path, capsys):
    overrides = [AfterOverride("pa.data", "sub.data", 0),
                 AfterOverride("pb.data", "sub.dta", 0)]
    rc, _ = _generate(tmp_path, TOGETHER, overrides, "decentralized")
    assert rc == 1
    assert "matches no cross-federate link" in capsys.readouterr().err
