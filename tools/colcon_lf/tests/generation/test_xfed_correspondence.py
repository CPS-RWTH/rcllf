_STOP_BUG = (
    "a separate arrive reaction sees the cross-federate records at (t + d, 0) "
    "and schedules the drain at (t + d, 1), which reactor-c refuses when a "
    "timeout stops the program at (t + d, 0): the records end SCHEDULE_REFUSED "
    "where one process delivers them")


def _reactions(group: str) -> list[tuple[str, str]]:
    """(trigger list, body) of every reaction of a reactor block."""
    out = []
    for head in re.finditer(r"reaction\(([^)]*)\)[^{]*\{=(.*?)=\}", group, re.S):
        out.append((head.group(1), head.group(2)))
    return out


def test_ingress_drain_is_triggered_by_its_xcorr_port(tmp_path):
    group = _reactor(_pubsub(tmp_path)["sub"]["lf"], "SubNode_DefaultGroup")
    on_port = [(t, b) for t, b in _reactions(group) if "xcorr_e0" in t.split(", ")]
    assert [t for t, _ in on_port] == ["corr_drain_e0, xcorr_e0"], f"{_STOP_BUG}:\n{group}"
    body = on_port[0][1]
    # Files the records, drains at this tag when they are due or the wake is
    # here, then re-arms, in that order; the re-arm stays the last line.
    arrive = body.index("ros2_lf_corr_arrive_remote(self, 0, &xcorr_e0->value)")
    gate = body.index("if (w == 0 || corr_drain_e0->is_present) {")
    drain = body.index('w = ros2_lf_corr_drain(self, 0, RID_SubNode_on_data, "data");')
    assert arrive < gate < drain, body
    assert body.strip().splitlines()[-1].strip() == (
        "if (w >= 0 && lf_schedule(corr_drain_e0, w) <= 0) "
        "{ ros2_lf_corr_schedule_refused(0); }"), body
    assert body.count("lf_schedule(") == 1, body


def test_cross_federate_fan_in_drains_both_members_in_one_reaction(tmp_path):
    # brake_fusion's radar and radar2 into radar_tracker: both members' records
    # come at one tag; the drain dispatches the rank-0 record at (t + d, 0) and
    # re-arms (t + d, 1) for the next, as one process does.
    out = _federate(tmp_path, [_pub("pa", "PubA"), _pub("pb", "PubB"), _sub("sub", "SubNode")],
                    [_tc("/data", ["pa", "pb"], ["sub"])],
                    {"pa": "front", "pb": "front", "sub": "back"})
    rows = [r for r in out["back"]["rows"] if r["topic"] == "/data"]
    assert sorted((r["status"], r["role"]) for r in rows) == [("admitted", "ingress")] * 2, rows
    ids = sorted(r["id"] for r in rows)
    group = _reactor(out["back"]["lf"], "SubNode_DefaultGroup")
    drains = [(t, b) for t, b in _reactions(group) if "ros2_lf_corr_drain(" in b]
    assert len(drains) == 1, group
    trig, body = drains[0]
    lead = ids[0]
    assert trig == ", ".join([f"corr_drain_e{lead}"] + [f"xcorr_e{e}" for e in ids]), \
        f"{_STOP_BUG}:\n{group}"
    for e in ids:
        assert f"ros2_lf_corr_arrive_remote(self, {e}, &xcorr_e{e}->value)" in body, body
    assert not [t for t, b in _reactions(group)
                if "ros2_lf_corr_arrive_remote" in b and "ros2_lf_corr_drain(" not in b], \
        f"{_STOP_BUG}:\n{group}"


