def _budget_override(max_exec_ns: int) -> AfterOverride:
    # Item5 piece D (CONS2 efa7e356): d = 5 ms, W = absent_after 1 ms, L + eps = 5 ms,
    # so the budget is d + W = 6 ms against 5 ms + max_exec.
    return AfterOverride("pub.data", "sub.data", 5_000_000, stp_offset_ns=1_000_000,
                         max_latency_ns=4_000_000, clock_error_ns=1_000_000,
                         max_exec_ns=max_exec_ns)


def test_decentralized_edge_over_its_budget_is_refused_at_generation(tmp_path, capsys):
    # d + W = 6 ms < L + eps + X + W_send = 4 + 1 + 2 + 0 ms: short by 1 ms.
    _pubsub(tmp_path, coordination="decentralized", expect_rc=1,
            overrides=[_budget_override(2_000_000)])
    err = capsys.readouterr().err
    assert "budget check refused" in err, err
    assert "'pub.data -> sub.data'" in err and "short by 1000000 ns" in err, err


