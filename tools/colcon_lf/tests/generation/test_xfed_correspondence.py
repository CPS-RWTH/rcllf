# ---------------------------------------------------------------------------
# A loop across federates. a (front) publishes /ab from a timer,
# b (back) relays it as /ba, and a's /ba callback publishes /out to c (front).
#
# A cross-federate edge is judged by the
# zero-delay cycle check like a local one, so the edge that closes the loop
# (/ba, last in connection order) is refused in the federated build exactly as
# in one process, whatever its link delay d and whether its joins are
# deferred. Before, the federated build admitted the loop when d covered the
# loop's take timeouts or the joins were deferred, and one
# process refused /ba, so admission depended on where the federation cut the
# graph. (The causal windows removed the slack rule, cycle_slack_below_timeout, with the
# timeout chain, since the cutoff now counts from each publication's commit.)
# ---------------------------------------------------------------------------

_XLOOP_5MS = [AfterOverride("a.ab", "b.ab", 5_000_000), AfterOverride("b.ba", "a.ba", 5_000_000)]
_XLOOP_ZERO = [AfterOverride("a.ab", "b.ab", 0), AfterOverride("b.ba", "a.ba", 0)]


def _xloop_nodes():
    a = _pub("a", "ANode", "ab")
    a.callbacks.append(CallbackInfo(name="on_ba", publishers_used=["out"]))
    a.subscribers.append(SubscriberInfo(topic="ba", message_type=MSG, callback="on_ba"))
    a.publishers.append(PublisherInfo(topic="out", message_type=MSG))
    nodes = [a, _sub("b", "BNode", "ab", publishes="ba"), _sub("c", "CNode", "out")]
    topics = [_tc("/ab", ["a"], ["b"]), _tc("/ba", ["b"], ["a"]), _tc("/out", ["a"], ["c"])]
    return nodes, topics


def _xloop(tmp_path, **bounds_kw):
    nodes, topics = _xloop_nodes()
    return _federate(tmp_path, nodes, topics, {"a": "front", "b": "back", "c": "front"},
                     **bounds_kw)


def _timeout_ns(init: str, edge_id: int) -> int:
    m = re.search(rf"register_corr_edge\(\{{{edge_id}, .*?, (\d+)LL, (\d+)LL, ", init)
    assert m, f"no register_corr_edge for edge {edge_id} in\n{init}"
    return int(m.group(2))


_T1 = {("b", "ab"): 1, ("a", "ba"): 1}
_OUT_RATE = {("a", "ba"): 100.0, ("c", "out"): 100.0}
