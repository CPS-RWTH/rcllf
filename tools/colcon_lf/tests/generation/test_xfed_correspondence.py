# ---------------------------------------------------------------------------
# The edge close runs after every user reaction of its reactor
# ---------------------------------------------------------------------------

def _close_before_user(lf: str) -> list[str]:
    """Per reactor block, the user reactions declared after a corr close.

    LF runs the reactions of one reactor at one tag in declaration order. A
    close declared before a timer reaction runs first at the stop tag (t, 0),
    and that timer's publish is committed after the reconcile.
    """
    late = []
    for block in re.split(r"\nreactor ", lf)[1:]:
        name = block.split(None, 1)[0]
        closed = False
        for head, body in re.findall(r"reaction\(([^)]*)\)[^{]*\{=(.*?)=\}", block, re.S):
            if "ros2_lf_corr_close(" in body:
                closed = True
            elif closed and head != "shutdown":
                late.append(f"{name}: reaction({head})")
    return late


