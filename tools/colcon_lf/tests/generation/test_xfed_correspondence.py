def _federate(tmp_path: Path, nodes, topics, node_fed: dict[str, str], *, k: int = 1,
              overrides=(), coordination: str = "centralized", timer_period_overrides=None,
              after_delay: str = "0 msec", bounds=None, reaction_order=None,
              expect_rc: int = 0, **bounds_kw) -> dict:
    """Generate per *node_fed* and return the json rows and LF text per federate.

    *bounds*, when given, maps the graph to its ``CorrBoundsConfig`` instead of
    ``declared(graph, k, **bounds_kw)``."""
    src = tmp_path / "packages/src/test_pkg/src"
    src.mkdir(parents=True, exist_ok=True)
    real = []
    for n in nodes:
        f = src / f"{n.name}.cpp"
        f.write_text("// generated by the test\n")
        real.append(dataclasses.replace(n, source_file=str(f)))
    graph = _graph(real, topics)
    adir = tmp_path / "lf-analysis/test_pkg/bringup"
    adir.mkdir(parents=True, exist_ok=True)
    sj = adir / "system.json"
    sj.write_text(json.dumps({"name": "bringup", "nodes": {}, "communication": {"topics": []}}))
    feds = list(dict.fromkeys(node_fed.values()))
    fmap = FederationMap(node_to_federate=dict(node_fed), federate_names=feds,
                         after_overrides=list(overrides), coordination=coordination)
    rc = _generate_federated(system_json=sj, graph=graph, fmap=fmap, after_delay=after_delay,
                             generate_launch=False, corr_bounds=bounds(graph) if bounds else declared(graph, k, **bounds_kw),
                             timer_period_overrides=timer_period_overrides,
                             reaction_order=reaction_order)
    assert rc == expect_rc
    if rc != 0:
        return {}
    gen = tmp_path / "lf-generated"
    out = {"top": (gen / FED / "lf/Bringup_federated.lf").read_text()}
    for fed in feds:
        out[fed] = {
            "rows": json.loads((gen / f"{FED}_{fed}/correspondence.json").read_text()),
            "lf": (gen / FED / f"lf/{fed}/{fed.capitalize()}.lf").read_text(),
            "init": (gen / f"{FED}_{fed}/src/ros2_lf_reaction_ids_init.cpp").read_text(),
        }
    return out


def _pubsub(tmp_path, **kw):
    return _federate(tmp_path, [_pub("pub", "PubNode"), _sub("sub", "SubNode")],
                     [_tc("/data", ["pub"], ["sub"])], {"pub": "pub", "sub": "sub"}, **kw)


def _row(rows, topic="/data"):
    found = [r for r in rows if r["topic"] == topic]
    assert len(found) == 1, f"{topic}: expected one row, got {rows}"
    return found[0]


