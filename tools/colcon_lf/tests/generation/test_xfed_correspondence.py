# ---------------------------------------------------------------------------
# Retain on a cross edge covers the clock bound eps
# ---------------------------------------------------------------------------

def _worst_case_retained(period_ns: int, k: int, d_ns: int, lag_ns: int, eps_ns: int) -> int:
    """Most samples one receiver holds at once, by brute force over a timer schedule.

    The sender's clock runs *eps_ns* ahead, so the k samples of tag t arrive at
    receiver time t - eps. The drain of tag t + d is as late as the binding
    allows, ending at t + d + L. A sample is held on the closed interval
    [t - eps, t + d + L]. Independent of the generator's N(W) arithmetic."""
    tags = [i * period_ns for i in range(200)]
    events = sorted({t - eps_ns for t in tags} | {t + d_ns + lag_ns for t in tags})
    return max(k * sum(1 for t in tags if t - eps_ns <= tau <= t + d_ns + lag_ns)
               for tau in events if tags[50] <= tau <= tags[150])


@pytest.mark.parametrize("k", [1, 3])
def test_cross_edge_retain_window_covers_the_clock_bound(tmp_path, k):
    # A retained sample lives from its arrival (no earlier than t - eps, the
    # sender commits at S(a) >= t on a clock at most eps apart) to the end of
    # its drain (no later than t + d + L, worker_lag_exceeded past L). The
    # binding refuses eps >= T on a cross edge, so the window is d + L + T.
    # d = 0, T = 100 ms, L = 2 T = 200 ms and a 10 ms timer with burst k:
    # W = 300 ms, N(W) = k (floor(300 / 10) + 1) = 31 k, retain 31 k + 1.
    # The earlier window d + L gives k (floor(200 / 10) + 1) + 1 = 21 k + 1,
    # below the 30 k samples held at once with eps = T - 1 ns.
    _federate(tmp_path, [_pub("pub", "PubNode"), _sub("sub", "SubNode")],
              [_tc("/data", ["pub"], ["sub"])], {"pub": "pub", "sub": "sub"}, k=k,
              timer_period_overrides={"pub": {"tick": 10.0}})
    man = json.loads((tmp_path / "lf-analysis/test_pkg/bringup/"
                      "rcllf_trace_manifest_federated.json").read_text())
    rows = [r for r in man["edges"] if r["topic"] == "/data"]
    assert {r["role"] for r in rows} == {"egress", "ingress"}
    held = _worst_case_retained(10_000_000, k, 0, 200_000_000, 100_000_000 - 1)
    assert held == 30 * k
    for r in rows:
        b = r["bounds"]
        assert b["inputs"]["T_ns"] == 100_000_000 and b["inputs"]["L_ns"] == 200_000_000
        assert b["retain"] >= held, f"{r['role']}: retain {b['retain']} < {held} held at once"
        assert b["retain"] == 31 * k + 1, r["role"]
        assert b["inputs"]["W_ns"] == 300_000_000, r["role"]
        assert b["inputs"]["eps_cover_ns"] == 100_000_000, r["role"]
