def _relay(tmp_path, feds=("front", "front", "back"), **kw):
    nodes = [_pub("src", "SrcNode", "a"), _sub("mid", "MidNode", "a", publishes="b"),
             _sub("sink", "SinkNode", "b")]
    return _federate(tmp_path, nodes,
                     [_tc("/a", ["src"], ["mid"]), _tc("/b", ["mid"], ["sink"])],
                     dict(zip(("src", "mid", "sink"), feds)), **kw)


def _reactor(lf: str, name: str) -> str:
    start = lf.index(f"reactor {name} {{")
    return lf[start:lf.index("\n}", start)]


def test_relay_publisher_is_admitted_with_a_flush(tmp_path, flush_on):
    # The relay drain runs at several microsteps of one time, and
    # one flush per time sends all its records. Admitted again,
    # the flush carries a COMPLETE number (it was once refused).
    out = _relay(tmp_path, overrides=[AfterOverride("mid.b", "sink.b", 5_000_000)])
    cross = _row(out["front"]["rows"], "/b")
    assert (cross["status"], cross["reason"], cross["role"]) == ("admitted", None, "egress")
    assert _row(out["back"]["rows"], "/b")["status"] == "admitted"
    local = _row(out["front"]["rows"], "/a")
    assert (local["status"], local["role"]) == ("admitted", "local")
    e = cross["id"]
    g = cross["global_id"]
    assert f"front.xcorr_g{g} -> back.xcorr_g{g} after 4999999 nsec" in out["top"]
    group = _reactor(out["front"]["lf"], "MidNode_DefaultGroup")
    assert f"logical action xcorr_flush_e{e}" in group
    # The local d = 0 edge merges its port into the drain.
    lid = local["id"]
    drain = group[group.index(f"reaction(corr_drain_e{lid}, corr_e{lid})"):]
    drain = drain[:drain.index("=}")]
    assert f"xcorr_flush_e{e}" in drain.splitlines()[0]
    assert f"ros2_lf_corr_flush_due({e})" in drain
    assert f"xcorr_e{e}" not in drain.replace(f"xcorr_flush_e{e}", "")
    # The flush is the reactor's first reaction, so at t + 1 ns it sends the
