"""Stub fan-in writers must land on one tag (probe P17h).

Two publisher nodes on one topic into one subscriber share one merged stub
input that carries only a write count, so the subscription takes samples in
arrival order. In a centralized federation with writer b after 5 msec and a
after 0, probe P17h handled 59 of a's and 59 of b's IDs at each other's tags.
The generator now refuses a fan-in whose writers can land on different tags:
unequal per-writer after delays, or writers in more than one federate. The
refusal also holds unfederated: narrowing it to federated programs was tried,
and a single-process run swapped 287 of 500 samples per writer.
"""

from __future__ import annotations

import dataclasses
import json
from pathlib import Path

import pytest

from colcon_lf.exec_config.connections import LinkDelay, LinkDelays
from colcon_lf.federation.partition import AfterOverride, FederationMap
from colcon_lf.generation.lf_emitter import emit_lf_system
from colcon_lf.generation.lf_generator import generate_lf_system
from colcon_lf.verb import generate as gen
from ..corr_declared import declared
from .test_correspondence_emission import _graph, _pub, _sub, _tc

TOGETHER = {"pa": "pubs", "pb": "pubs", "sub": "sub"}
APART = {"pa": "pa", "pb": "pb", "sub": "sub"}
B_AFTER_NS = 5_000_000


def _nodes(tmp_path: Path):
    src = tmp_path / "packages/src/test_pkg/src"
    src.mkdir(parents=True, exist_ok=True)
    nodes = []
    for n in [_pub("pa", "PubA"), _pub("pb", "PubB"), _sub("sub", "SubNode")]:
        f = src / f"{n.name}.cpp"
        f.write_text("// generated by the test\n")
        nodes.append(dataclasses.replace(n, source_file=str(f)))
    return nodes


def _unequal_topics():
    """One topic, writer pb's link after 5 msec, writer pa's after 0."""
    return [dataclasses.replace(_tc("/data", ["pa"], ["sub"]), after_delay_ns=0),
            dataclasses.replace(_tc("/data", ["pb"], ["sub"]), after_delay_ns=B_AFTER_NS)]


def _b_link_delay() -> LinkDelays:
    """execution.yaml ``connections: /data: links: pb -> sub: after_delay 5 msec``."""
    ld = LinkDelays()
    ld.by_pair[("/data", "pb", "sub")] = LinkDelay(
        ns=B_AFTER_NS, literal="5 msec", reason="test", source="",
        evidence="execution.yaml:connections./data.links.pb -> sub")
    return ld


def _generate_federated(tmp_path: Path, node_fed, overrides=(), coordination="centralized",
                        topics=None, link_delays=None, corr_bounds=None) -> int:
    """Run the real federated generator on pa, pb -> sub, return its exit code.

    *corr_bounds* defaults to ``declared(graph, 1)``, so every edge that can be
    admitted is.
    """
    topics = topics if topics is not None else [_tc("/data", ["pa", "pb"], ["sub"])]
    graph = _graph(_nodes(tmp_path), topics)
    adir = tmp_path / "lf-analysis/test_pkg/bringup"
    adir.mkdir(parents=True, exist_ok=True)
    sj = adir / "system.json"
    sj.write_text(json.dumps({"name": "bringup", "nodes": {}, "communication": {"topics": []}}))
    fmap = FederationMap(node_to_federate=dict(node_fed),
                         federate_names=list(dict.fromkeys(node_fed.values())),
                         after_overrides=list(overrides), coordination=coordination)
    bounds = declared(graph, 1) if corr_bounds is None else corr_bounds
    return gen._generate_federated(system_json=sj, graph=graph, fmap=fmap, after_delay="0 msec",
                                   generate_launch=False, corr_bounds=bounds,
                                   link_delays=link_delays)


def _refused(rc: int, err: str) -> None:
    assert rc == 1 and "legacy fan-in into sub.data on topic /data" in err, (
        f"split fan-in into sub.data was not refused at generation (exit {rc}):\n{err}")


@pytest.mark.parametrize("coordination", ["centralized", "decentralized"])
def test_unequal_after_delays_are_refused(tmp_path, capsys, coordination):
    overrides = [AfterOverride("pa.data", "sub.data", 0),
                 AfterOverride("pb.data", "sub.data", B_AFTER_NS)]
    rc = _generate_federated(tmp_path, TOGETHER, overrides, coordination)
    err = capsys.readouterr().err
    _refused(rc, err)
    assert "pb.data (federate pubs, after 5000000 ns)" in err, err
    assert "Fix: put every publisher node of /data into one federate with one after delay " \
        "to sub.data, or publish /data from one node" in err, err


@pytest.mark.parametrize("coordination", ["centralized", "decentralized"])
def test_writers_in_two_federates_are_refused(tmp_path, capsys, monkeypatch, coordination):
    # d = 0 is admitted, so the legacy fan-in needs a refused
    # edge: 1 ns under the flush is refused (xfed_flush_min).
    monkeypatch.setenv("RCLLF_XFED_FLUSH", "1")
    overrides = [AfterOverride("pa.data", "sub.data", 1),
                 AfterOverride("pb.data", "sub.data", 1)]
    rc = _generate_federated(tmp_path, APART, overrides, coordination)
    err = capsys.readouterr().err
    _refused(rc, err)
    assert "pa.data (federate pa, after 1 ns), pb.data (federate pb, after 1 ns)" in err, err


def test_one_writer_local_one_remote_is_refused(tmp_path, capsys):
    # The local writer runs its link delay, the remote one the default cross delay.
    rc = _generate_federated(tmp_path, {"pa": "pa", "pb": "sub", "sub": "sub"})
    _refused(rc, capsys.readouterr().err)


@pytest.mark.parametrize("coordination", ["centralized", "decentralized"])
def test_exec_config_link_delay_inside_one_federate_is_refused(tmp_path, capsys, coordination):
    # The federated check must see execution.yaml's per-link
    # delays, the per-federate generator applies them to the intra links.
    rc = _generate_federated(tmp_path, {"pa": "f", "pb": "f", "sub": "f"}, (), coordination,
                             link_delays=_b_link_delay())
    err = capsys.readouterr().err
    _refused(rc, err)
    assert "pa.data (federate f, after 0 ns), pb.data (federate f, after 5000000 ns)" in err, err


def test_writers_together_with_one_delay_are_accepted_without_publish_counts(
        tmp_path, capsys, monkeypatch):
    # The fan-in itself lands on one tag. Generation refuses it only where the
    # link carries the tag log (test_xtag_link.py); a count-only link is fine.
    monkeypatch.setenv("RCLLF_COUNT_PUBLISHES", "0")
    overrides = [AfterOverride("pa.data", "sub.data", 0),
                 AfterOverride("pb.data", "sub.data", 0)]
    rc = _generate_federated(tmp_path, TOGETHER, overrides)
    assert rc == 0, capsys.readouterr().err


def test_unfederated_unequal_link_delays_are_refused(tmp_path):
    # One program still splits the fan-in: a's sample lands at t, b's at
    # t + 5 msec, and the merged port pops them in arrival order.
    with pytest.raises(ValueError, match=r"legacy fan-in into sub\.data on topic /data: "
                       r"writers pa\.data \(federate -, after 0 ns\), "
                       r"pb\.data \(federate -, after 5000000 ns\)"):
        generate_lf_system(_graph(_nodes(tmp_path), _unequal_topics()))


def test_unfederated_exec_config_link_delay_is_refused(tmp_path):
    graph = _graph(_nodes(tmp_path), [_tc("/data", ["pa", "pb"], ["sub"])])
    with pytest.raises(ValueError) as exc:
        generate_lf_system(graph, link_delays=_b_link_delay())
    msg = str(exc.value)
    assert "pb.data (federate -, after 5000000 ns)" in msg, msg
    # No federates to move publishers into: the hint is one equal delay.
    assert "Fix: give every publisher node of /data one equal after delay to sub.data, " \
        "or publish /data from one node" in msg, msg
    assert "federate with" not in msg, msg


def test_unfederated_equal_link_delays_are_accepted(tmp_path):
    topics = [dataclasses.replace(t, after_delay_ns=B_AFTER_NS) for t in _unequal_topics()]
    text = emit_lf_system(generate_lf_system(_graph(_nodes(tmp_path), topics)))
    assert "pa.data -> sub.data after 5 msec" in text, text
    assert "pb.data -> sub.data_fanin_1 after 5 msec" in text, text
