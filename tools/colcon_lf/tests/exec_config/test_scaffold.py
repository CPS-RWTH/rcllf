"""Tests for scaffold.py: reference emission, sparse creation, stale report.

Also asserts the never-rewrites-user-file guarantee (00_design.md section
2.1/4 mode 2) and idempotence across repeated runs.
"""

from __future__ import annotations

import textwrap

from colcon_lf.exec_config.scaffold import (
    REFERENCE_FILENAME,
    SPARSE_FILENAME,
    scaffold,
)

from .conftest import make_graph, make_node


class TestFirstScaffold:
    def test_creates_both_files(self, tmp_path):
        graph = make_graph({"n": make_node("n", subscriptions=["t"])})
        result = scaffold(tmp_path, graph)
        assert result.sparse_created is True
        assert (tmp_path / REFERENCE_FILENAME).is_file()
        assert (tmp_path / SPARSE_FILENAME).is_file()

    def test_sparse_file_is_minimal_and_parseable(self, tmp_path):
        import yaml

        graph = make_graph({"n": make_node("n")})
        scaffold(tmp_path, graph)
        content = (tmp_path / SPARSE_FILENAME).read_text()
        parsed = yaml.safe_load(content)
        assert parsed["schema_version"] == 1
        assert parsed["defaults"] == {}

    def test_reference_file_contains_node_and_topic_keys(self, tmp_path):
        graph = make_graph({
            "/robot_1/subscriber_node": make_node(
                "subscriber_node",
                class_name="SubscriberNode",
                subscriptions=["sensor_data"],
            )
        })
        scaffold(tmp_path, graph)
        content = (tmp_path / REFERENCE_FILENAME).read_text()
        assert "/robot_1/subscriber_node" in content
        assert "sensor_data" in content
        assert "take_mode" in content
        assert "#   maxwait_ms (default: 100)" in content
        # Registry doc lines are present as comments.
        assert "GENERATED by" in content

    def test_reference_file_is_all_comments(self, tmp_path):
        graph = make_graph({"n": make_node("n", subscriptions=["t"])})
        scaffold(tmp_path, graph)
        content = (tmp_path / REFERENCE_FILENAME).read_text()
        for line in content.splitlines():
            if line.strip():
                assert line.lstrip().startswith("#")


class TestNeverRewritesUserFile:
    def test_existing_sparse_file_untouched(self, tmp_path):
        graph = make_graph({"n": make_node("n", subscriptions=["t"])})
        sparse_path = tmp_path / SPARSE_FILENAME
        user_content = textwrap.dedent("""\
            schema_version: 1
            defaults:
              take_mode: block
        """)
        sparse_path.write_text(user_content, encoding="utf-8")

        result = scaffold(tmp_path, graph)

        assert result.sparse_created is False
        assert sparse_path.read_text() == user_content

    def test_reference_file_always_regenerated(self, tmp_path):
        graph = make_graph({"n": make_node("n")})
        (tmp_path / REFERENCE_FILENAME).write_text("stale content", encoding="utf-8")
        scaffold(tmp_path, graph)
        content = (tmp_path / REFERENCE_FILENAME).read_text()
        assert "stale content" not in content
        assert "GENERATED by" in content


class TestIdempotence:
    def test_running_twice_is_stable(self, tmp_path):
        graph = make_graph({"n": make_node("n", subscriptions=["t"])})
        result1 = scaffold(tmp_path, graph)
        sparse_after_first = (tmp_path / SPARSE_FILENAME).read_text()
        result2 = scaffold(tmp_path, graph)
        sparse_after_second = (tmp_path / SPARSE_FILENAME).read_text()

        assert result1.sparse_created is True
        assert result2.sparse_created is False
        assert sparse_after_first == sparse_after_second


class TestStaleReport:
    def test_stale_node_reported(self, tmp_path):
        graph = make_graph({"n": make_node("n")})
        sparse_path = tmp_path / SPARSE_FILENAME
        sparse_path.write_text(textwrap.dedent("""\
            schema_version: 1
            nodes:
              renamed_or_deleted_node:
                take_timeout_ms: 250
        """), encoding="utf-8")

        result = scaffold(tmp_path, graph)
        assert "renamed_or_deleted_node" in result.stale_nodes
        # Never rewritten despite being stale.
        assert "renamed_or_deleted_node" in sparse_path.read_text()

    def test_stale_subscription_topic_reported(self, tmp_path):
        graph = make_graph({"n": make_node("n", subscriptions=["t"])})
        sparse_path = tmp_path / SPARSE_FILENAME
        sparse_path.write_text(textwrap.dedent("""\
            schema_version: 1
            subscriptions:
              n:
                nonexistent_topic:
                  take_mode: block
        """), encoding="utf-8")

        result = scaffold(tmp_path, graph)
        assert ("n", "nonexistent_topic") in result.stale_subscription_topics

    def test_no_stale_entries_when_config_matches_model(self, tmp_path):
        graph = make_graph({"n": make_node("n", subscriptions=["t"])})
        sparse_path = tmp_path / SPARSE_FILENAME
        sparse_path.write_text(textwrap.dedent("""\
            schema_version: 1
            subscriptions:
              n:
                t:
                  take_mode: block
        """), encoding="utf-8")

        result = scaffold(tmp_path, graph)
        assert result.stale_nodes == []
        assert result.stale_subscription_topics == []

    def test_slash_tolerant_entries_not_reported_stale(self, tmp_path):
        graph = make_graph({"n": make_node("n", subscriptions=["t"])})
        sparse_path = tmp_path / SPARSE_FILENAME
        sparse_path.write_text(textwrap.dedent("""\
            schema_version: 1
            subscriptions:
              n:
                /t:
                  take_mode: block
        """), encoding="utf-8")

        result = scaffold(tmp_path, graph)
        assert result.stale_subscription_topics == []
